import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const localeDir = join(root, 'src', 'locales');
const outputPath = join(localeDir, 'registry.ts');
const checkOnly = process.argv.includes('--check');

function identifier(code) {
  const parts = code.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const first = (parts.shift() || 'locale').replace(/^([0-9])/, '_$1');
  return first + parts.map(part => part.slice(0, 1).toUpperCase() + part.slice(1)).join('');
}

const entries = [];
for (const name of (await readdir(localeDir)).filter(name => name.endsWith('.json')).sort()) {
  const code = name.slice(0, -5);
  let value;
  try {
    value = JSON.parse(await readFile(join(localeDir, name), 'utf8'));
  } catch {
    continue;
  }
  if (!value?.meta || typeof value.meta.nativeName !== 'string' || !['ltr', 'rtl'].includes(value.meta.direction)) continue;
  entries.push({ code, name, id: identifier(code) });
}

if (!entries.some(entry => entry.code === 'en') || !entries.some(entry => entry.code === 'tr')) {
  throw new Error('Modern locale registry requires en.json and tr.json.');
}

const imports = entries.map(entry => `import ${entry.id} from '@/locales/${entry.name}';`).join('\n');
const map = entries.map(entry => `  ${JSON.stringify(entry.code)}: ${entry.id}`).join(',\n');
const output = `// AUTO-GENERATED by scripts/generate-locale-registry.mjs.
// Do not edit manually. Add/update a modern JSON locale and run npm run i18n:generate.

${imports}

export const LOCALE_MODULES = {
${map}
} as const;

export type LocaleCode = keyof typeof LOCALE_MODULES;
`;

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== output) {
    console.error('Locale registry is stale. Run: npm run i18n:generate');
    console.error('Expected modern locales:', entries.map(entry => entry.code).join(', '));
    process.exit(1);
  }
  console.log(`✓ Locale registry current: ${entries.length} modern locale(s).`);
} else {
  await writeFile(outputPath, output, 'utf8');
  console.log(`✓ Generated ${relative(root, outputPath)} with ${entries.length} modern locale(s).`);
}
